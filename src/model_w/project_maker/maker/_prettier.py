import re
from collections.abc import Mapping
from pathlib import Path

from node_edge import NodeEngine

from ._base import BaseComponent

#: Directories never worth looking into
SKIPPED_DIRS = {".git", "node_modules", ".venv", ".svelte-kit"}

#: Files Prettier can format (checked before asking Prettier, which is slower)
SUPPORTED = re.compile(
    r".*\.([jt]sx?|json|md|html?|svelte|ya?ml|s?css)$", re.IGNORECASE
)


class PrettierComponent(BaseComponent):
    """
    Formats the whole generated project with Prettier (Markdown, YAML, JSON,
    TS, Svelte, SCSS...), whichever component the files come from.

    It runs once everything else is done (it must be the last component), so
    that:

    - The configuration and ignore files of the generated project exist, so
      each file gets formatted with the configuration that the developers
      will use (the closest .prettierrc and .prettierignore).
    - Files generated by other components (like the API's TypeScript client)
      get formatted as well.
    """

    def __init__(self):
        self.ne = NodeEngine(
            {
                "dependencies": {
                    "prettier": "3.9.x",
                    "prettier-plugin-svelte": "4.1.x",
                }
            }
        )
        self.prettier = None
        self.plugins: list[str] = []

    def start(self) -> None:
        """
        Warming up Node Edge and getting a proxy to Prettier.

        Prettier 3 doesn't auto-load plugins and would otherwise look for
        them next to the generated files (which have no node_modules yet),
        so we point it at the absolute path of the plugin installed in the
        Node Edge environment.
        """

        self.report("Starting Prettier")
        self.ne.start()
        self.prettier = self.ne.import_from("prettier")
        node_modules = self.ne.ensure_env_dir() / "node_modules"
        self.plugins = [f"{node_modules / 'prettier-plugin-svelte' / 'plugin.js'}"]

    def stop(self) -> None:
        """
        Kill Node Edge
        """

        self.ne.stop()

    def accept(self, path: Path, context: Mapping):
        """
        Files are rendered by the other components, this one only formats.
        """

        return False

    def finalize(self, root: Path, context: Mapping) -> None:
        """
        Formats every file of the project that Prettier supports.

        Parameters
        ----------
        root
            Root of the generated project
        context
            Global context of the generation
        """

        self.report("Formatting with Prettier")

        for file in self.files(root):
            self.format(root, file)

    def files(self, root: Path):
        """
        The files of the project that Prettier may format, outside of the
        skipped directories.

        Parameters
        ----------
        root
            Root of the generated project
        """

        for path in sorted(root.iterdir()):
            if path.is_dir():
                if path.name not in SKIPPED_DIRS:
                    yield from self.files(path)
            elif path.is_file() and SUPPORTED.match(path.name):
                yield path

    def ignore_file(self, root: Path, file: Path) -> Path:
        """
        The front has its own ignore file (Prettier runs from there), the
        rest of the project uses the root one.

        Parameters
        ----------
        root
            Root of the generated project
        file
            File to format
        """

        front = root / "front"

        if file.is_relative_to(front):
            return front / ".prettierignore"

        return root / ".prettierignore"

    def format(self, root: Path, file: Path) -> None:
        """
        Formats a file in place, if Prettier supports it and it's not ignored.

        Parameters
        ----------
        root
            Root of the generated project
        file
            File to format
        """

        info = self.ne.resolve(
            self.prettier.getFileInfo(
                f"{file}",
                {
                    "ignorePath": f"{self.ignore_file(root, file)}",
                    "plugins": self.plugins,
                },
            )
        )

        if info.get("ignored") or not (parser := info.get("inferredParser")):
            return

        options = self.ne.resolve(
            self.prettier.resolveConfig(f"{file}", {"editorconfig": False})
        )
        options = dict(options or {})
        options.update(parser=parser, plugins=self.plugins, filepath=f"{file}")

        content = file.read_text(encoding="utf-8")
        formatted = self.ne.resolve(self.prettier.format(content, options))

        if formatted != content:
            file.write_text(formatted, encoding="utf-8", newline="\n")
